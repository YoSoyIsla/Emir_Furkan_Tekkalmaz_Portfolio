// scripts/build-images.mjs
//
// Generates the optimized artwork images served by the site from the masters in /works:
//   public/works/<id>.webp        full resolution (long edge capped at FULL_MAX_WIDTH wide)
//   public/works/<id>-<w>.webp    responsive widths for srcset (RESPONSIVE_WIDTHS)
//   public/works/<id>-og.jpg      1200px JPEG for social sharing previews
// and writes works-images.generated.js with the final pixel dimensions.
//
// Usage: npm run images            (add --clean to delete stale files in public/works)

import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import sharp from 'sharp';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const srcDir = path.join(root, 'works');
const outDir = path.join(root, 'public', 'works');
const manifestPath = path.join(root, 'works-images.generated.js');
const clean = process.argv.includes('--clean');

// The data module imports the manifest; make sure it exists before importing.
try {
    await fs.access(manifestPath);
} catch {
    await fs.writeFile(manifestPath, 'export const IMAGE_DIMENSIONS = {};\n');
}
const { WORKS, RESPONSIVE_WIDTHS, FULL_MAX_WIDTH } = await import('../works-data.js');

const WEBP_FULL = { quality: 82, effort: 6, smartSubsample: true };
const WEBP_RESPONSIVE = { quality: 78, effort: 6, smartSubsample: true };
const OG_WIDTH = 1200;

/** Bounding box of fully opaque pixels (masters can have a 1px transparent edge). */
async function opaqueBox(file) {
    const img = sharp(file);
    const meta = await img.metadata();
    if (!meta.hasAlpha) return { left: 0, top: 0, width: meta.width, height: meta.height };
    const { data, info } = await img.extractChannel('alpha').raw().toBuffer({ resolveWithObject: true });
    let top = info.height, left = info.width, bottom = -1, right = -1;
    for (let y = 0; y < info.height; y++) {
        const row = y * info.width;
        for (let x = 0; x < info.width; x++) {
            if (data[row + x] === 255) {
                if (y < top) top = y;
                if (y > bottom) bottom = y;
                if (x < left) left = x;
                if (x > right) right = x;
            }
        }
    }
    return { left, top, width: right - left + 1, height: bottom - top + 1 };
}

await fs.mkdir(outDir, { recursive: true });
const dimensions = {};
const expected = new Set();

for (const work of WORKS) {
    const file = path.join(srcDir, work.source);
    const box = await opaqueBox(file);
    const base = () => sharp(file).extract(box).removeAlpha();

    const fullWidth = Math.min(box.width, FULL_MAX_WIDTH);
    const fullHeight = Math.round((box.height * fullWidth) / box.width);
    dimensions[work.id] = [fullWidth, fullHeight];

    const jobs = [];
    const fullName = `${work.id}.webp`;
    expected.add(fullName);
    jobs.push(base().resize({ width: fullWidth, height: fullHeight, fit: 'fill' }).webp(WEBP_FULL).toFile(path.join(outDir, fullName)));

    for (const w of RESPONSIVE_WIDTHS.filter((w) => w < fullWidth)) {
        const name = `${work.id}-${w}.webp`;
        expected.add(name);
        jobs.push(base().resize({ width: w }).webp(WEBP_RESPONSIVE).toFile(path.join(outDir, name)));
    }

    const ogName = `${work.id}-og.jpg`;
    expected.add(ogName);
    jobs.push(base().resize({ width: Math.min(OG_WIDTH, fullWidth) }).jpeg({ quality: 80, mozjpeg: true }).toFile(path.join(outDir, ogName)));

    await Promise.all(jobs);
    console.log(`${work.id.padEnd(36)} ${work.source.padEnd(38)} -> ${fullWidth}x${fullHeight}`);
}

const body = Object.entries(dimensions)
    .map(([id, [w, h]]) => `    ${id}: [${w}, ${h}],`)
    .join('\n');
await fs.writeFile(
    manifestPath,
    `// Generated by scripts/build-images.mjs - do not edit by hand.\n` +
    `// Pixel dimensions of the full-resolution image in /public/works/<id>.webp.\n` +
    `export const IMAGE_DIMENSIONS = {\n${body}\n};\n`,
);

if (clean) {
    for (const name of await fs.readdir(outDir)) {
        if (!expected.has(name)) {
            await fs.unlink(path.join(outDir, name));
            console.log(`removed stale public/works/${name}`);
        }
    }
}

console.log(`\n${WORKS.length} works processed, ${expected.size} files in public/works.`);
